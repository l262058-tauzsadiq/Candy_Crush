void displayBoard(sf::RenderWindow& window_screen, int size)
{
    red_candy.loadFromFile("assets/redcandy.png");
    blue_candy.loadFromFile("assets/bluecandy.png");
    orange_candy.loadFromFile("assets/orangecandy.png");
    green_candy.loadFromFile("assets/greencandy.png");
    purple_candy.loadFromFile("assets/purplecandy.png");

    window_screen.clear();
    background(window_screen);

    // these variables are used for dimensions and gaps for board and candies 
    const int gap = 4, candy_size = 48;
    int cell_size, board_size, left, top;

    if (size == 5) {
        cell_size = 100;
        board_size = 516;
        left = 117;
        top = 192;
    }
    else if (size == 8) {
        cell_size = 75;
        board_size = 628;
        left = 61;
        top = 136;
    }
    else if (size == 10) {
        cell_size = 60;
        board_size = 636;
        left = 57;
        top = 132;
    }
    else {
        return;
    }

    sf::RectangleShape board_bg(sf::Vector2f(board_size, board_size));
    board_bg.setPosition(left, top);
    board_bg.setFillColor(sf::Color(30, 30, 30, 180));
    window_screen.draw(board_bg);

    for (int row = 0; row < size; ++row) {
        for (int col = 0; col < size; ++col) {
            sf::Sprite candy;

            if (board[row][col] == 0) {
                candy.setTexture(red_candy);
            }
            else if (board[row][col] == 1) {
                candy.setTexture(blue_candy);
            }
            else if (board[row][col] == 2) {
                candy.setTexture(orange_candy);
            }
            else if (board[row][col] == 3) {
                candy.setTexture(green_candy);
            }
            else if (board[row][col] == 4) {
                candy.setTexture(purple_candy);
            }

            const sf::FloatRect bounds = candy.getLocalBounds();

            // every image has different dimensions therfore i was unable to 
            // make them them perfect sized and set their postion
            // these formulas are generated by ai. 
            candy.setScale(candy_size / bounds.width, candy_size / bounds.height);
            candy.setPosition(left + col * (cell_size + gap) + (cell_size - candy_size) / 2.f,top + row * (cell_size + gap) + (cell_size - candy_size) / 2.f);

            window_screen.draw(candy);
        }
    }
}
